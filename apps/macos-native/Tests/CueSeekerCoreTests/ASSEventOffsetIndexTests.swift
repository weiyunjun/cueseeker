    let ep2SSA = try fixture.writeRawSubtitle(name: "EP02.ssa", data: Data(legacySSA.utf8))
    try fixture.writeVideo(name: "EP02.mkv")

    // 3. Heavy multi-thousand-event ASS to verify compact zlib compression
    var heavyLines: [String] = [
        "[Script Info]",
        "ScriptType: v4.00+",
        "PlayResX: 1920",
        "PlayResY: 1080",
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
        "Dialogue: 0,0:00:01.00,0:00:04.00,Default,,0,0,0,,Opening dialogue line for cue indexing"
    ]
    heavyLines.reserveCapacity(5_010)
    for frame in 0..<5_000 {
        let startCs = frame * 4
        let endCs = startCs + 4
        let sSec = (startCs / 100) % 60
        let sMin = (startCs / 6000) % 60
        let sRem = startCs % 100
        let eSec = (endCs / 100) % 60
        let eMin = (endCs / 6000) % 60
        let eRem = endCs % 100
        let startTag = String(format: "0:%02d:%02d.%02d", sMin, sSec, sRem)
        let endTag = String(format: "0:%02d:%02d.%02d", eMin, eSec, eRem)
        heavyLines.append(
            "Dialogue: 2,\(startTag),\(endTag),FX,,0,0,0,,{\\pos(\(frame % 1920),\(frame % 1080))\\p1}m 0 0 l 20 0 20 20 0 20{\\p0}"
        )
    }
    let heavyASSData = Data(heavyLines.joined(separator: "\n").utf8)
    let ep3HeavyASS = try fixture.writeRawSubtitle(name: "EP03.ass", data: heavyASSData)
    try fixture.writeVideo(name: "EP03.mkv")

    let indexer = SubtitleIndexer()
    let indexResult = try indexer.index(folder: fixture.root, into: fixture.indexingDatabase)
    #expect(indexResult.indexedSubtitleFiles == 3)
    #expect(indexResult.failedFiles.isEmpty)

    let playbackDB = try PlaybackSubtitleDatabase(path: fixture.databaseURL, access: .readOnly)
    let renderCache: any PlaybackSubtitleRenderCacheProviding = PlaybackSubtitleRenderCacheReader(
        databaseURL: fixture.databaseURL
    )

    // Verify EP01.ass header, event count (all 6 renderable Dialogue lines retained, Comment excluded),
    // and exact source-file line order on window query [5_000 ..< 6_000].
    let ep1Index = try #require(try renderCache.validatedASSEventOffsetIndex(forSubtitleFile: ep1ASS))
    #expect(ep1Index.encodingName == "UTF-8")
    #expect(ep1Index.eventCount == 6)
    #expect(ep1Index.headerText.contains("[Script Info]"))
    #expect(ep1Index.headerText.contains("PlayResX: 1920"))
    #expect(ep1Index.headerText.contains("[V4+ Styles]"))
    #expect(ep1Index.headerText.contains("[Events]"))
    #expect(!ep1Index.headerText.contains("Aegisub"))
    #expect(!ep1Index.headerText.contains("Dialogue:"))

    let windowRanges = ep1Index.overlappingEvents(in: 5_000..<6_000)
    #expect(windowRanges.count == 5)
    let slicedLines = try #require(try ep1Index.readAndDecodeEventLines(windowRanges, from: ep1ASS))
    #expect(slicedLines == [
        "Dialogue: 0,0:00:05.00,0:00:08.00,JP,,0,0,0,,君の声が聞こえる, 今ここで",
        "Dialogue: 0,0:00:05.00,0:00:08.00,CN,,0,0,0,,此刻在这里，能听见你的声音",
        "Dialogue: 3,0:00:05.02,0:00:05.06,FX,,0,0,0,,{\\pos(960,540)\\fscx120}✦",
        "Dialogue: 4,0:00:05.00,0:00:06.50,FX,,0,0,0,,{\\p1}m 0 0 l 120 0 120 40 0 40{\\p0}",
        "Dialogue: 9,0:00:05.01,0:00:07.00,FX,,0,0,0,,{\\an8}置底分组特效标题"
    ])

    // Silent window returns empty array on the validated in-memory index.
    let silentWindow = ep1Index.overlappingEvents(in: 10_000..<15_000)
    #expect(silentWindow.isEmpty)

    // Verify EP02.ssa legacy format
    let ep2Index = try #require(try playbackDB.validatedASSEventOffsetIndex(forSubtitleFile: ep2SSA))
    #expect(ep2Index.eventCount == 1)
    let ep2Lines = try #require(
        try ep2Index.readAndDecodeEventLines(ep2Index.activeEvents(atMilliseconds: 3_000), from: ep2SSA)
    )
    #expect(ep2Lines == [
        "Dialogue: Marked=0,0:00:02.00,0:00:04.50,Default,NTP,0000,0000,0000,!Effect,Classic SSA line"
    ])

    // Verify EP03.ass heavy particle index compression compactness
    let ep3Index = try #require(try playbackDB.validatedASSEventOffsetIndex(forSubtitleFile: ep3HeavyASS))
    #expect(ep3Index.eventCount == 5_001)
    let compressedByteCountString = try #require(
        try sqliteStringValue(
            at: fixture.databaseURL,
            sql: """
                SELECT CAST(length(idx.compressed_events) AS TEXT)
                FROM ass_event_offset_indexes idx
                JOIN subtitle_files sf ON sf.id = idx.subtitle_file_id
                WHERE sf.subtitle_path LIKE '%/EP03.ass';
                """
        )
    )
    let compressedByteCount = try #require(Int(compressedByteCountString))
    // Raw 5001 * 16 = 80,016 bytes; zlib compressed payload is significantly smaller than raw unpacked size.
    #expect(compressedByteCount > 0)
    #expect(compressedByteCount < 5_001 * 16)
}

@Test
func slicesExactByteOffsetsAcrossUTF8BOMUTF16LEUTF16BEUTF32LEAndGB18030Encodings() throws {
    let fixture = try ASSEventOffsetTestFixture()
    defer { fixture.cleanUp() }

    let scriptLines = [
        "[Script Info]",
        "ScriptType: v4.00+",
        "PlayResX: 1280",
        "PlayResY: 720",
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
        "Dialogue: 0,0:00:01.00,0:00:03.00,Default,,0,0,0,,第一行多编码测试：中文与ASCII混合",
        "Dialogue: 0,0:00:04.00,0:00:06.50,Default,,0,0,0,,第二行边界字符：上（U+4E0A 低字节为 0x0A）"
    ]
    // Intentionally use CRLF and no trailing newline on the final line to exercise exact byte boundaries.
    let crlfScript = scriptLines.joined(separator: "\r\n")

    var utf8BOM = Data([0xEF, 0xBB, 0xBF])
    utf8BOM.append(Data(crlfScript.utf8))
    let fUTF8BOM = try fixture.writeRawSubtitle(name: "Enc1_UTF8BOM.ass", data: utf8BOM)
    try fixture.writeVideo(name: "Enc1_UTF8BOM.mkv")

    var utf16LE = Data([0xFF, 0xFE])
    utf16LE.append(try #require(crlfScript.data(using: .utf16LittleEndian)))
    let fUTF16LE = try fixture.writeRawSubtitle(name: "Enc2_UTF16LE.ass", data: utf16LE)
    try fixture.writeVideo(name: "Enc2_UTF16LE.mkv")

    var utf16BE = Data([0xFE, 0xFF])
    utf16BE.append(try #require(crlfScript.data(using: .utf16BigEndian)))
    let fUTF16BE = try fixture.writeRawSubtitle(name: "Enc3_UTF16BE.ass", data: utf16BE)
    try fixture.writeVideo(name: "Enc3_UTF16BE.mkv")

    var utf32LE = Data([0xFF, 0xFE, 0x00, 0x00])
    utf32LE.append(try #require(crlfScript.data(using: .utf32LittleEndian)))
    let fUTF32LE = try fixture.writeRawSubtitle(name: "Enc4_UTF32LE.ass", data: utf32LE)
    try fixture.writeVideo(name: "Enc4_UTF32LE.mkv")

    let gb18030CF = CFStringEncoding(CFStringEncodings.GB_18030_2000.rawValue)
    let gb18030Encoding = String.Encoding(rawValue: CFStringConvertEncodingToNSStringEncoding(gb18030CF))
    let gb18030Data = try #require(crlfScript.data(using: gb18030Encoding))
    let fGB18030 = try fixture.writeRawSubtitle(name: "Enc5_GB18030.ass", data: gb18030Data)
    try fixture.writeVideo(name: "Enc5_GB18030.mkv")

    let result = try SubtitleIndexer().index(folder: fixture.root, into: fixture.indexingDatabase)
    #expect(result.indexedSubtitleFiles == 5)
    #expect(result.failedFiles.isEmpty)

    let playbackDB = try PlaybackSubtitleDatabase(path: fixture.databaseURL, access: .readOnly)
    for subtitleURL in [fUTF8BOM, fUTF16LE, fUTF16BE, fUTF32LE, fGB18030] {
        let index = try #require(try playbackDB.validatedASSEventOffsetIndex(forSubtitleFile: subtitleURL))
        #expect(index.eventCount == 2)

        let secondOnly = index.overlappingEvents(in: 4_500..<5_000)
        #expect(secondOnly.count == 1)
        let decodedSecond = try #require(try index.readAndDecodeEventLines(secondOnly, from: subtitleURL))
        #expect(decodedSecond == [
            "Dialogue: 0,0:00:04.00,0:00:06.50,Default,,0,0,0,,第二行边界字符：上（U+4E0A 低字节为 0x0A）"
        ])

        let allEvents = index.overlappingEvents(in: 0..<10_000)
        let decodedAll = try #require(try index.readAndDecodeEventLines(allEvents, from: subtitleURL))
        #expect(decodedAll == Array(scriptLines.suffix(2)))
    }
}

@Test
func marksEmbeddedFontsOrMidStreamFormatChangeIneligibleAndSkipsRescanningOnRepeatIndex() throws {
    let fixture = try ASSEventOffsetTestFixture()
    defer { fixture.cleanUp() }

    let embeddedFontASS = """
    [Script Info]
    ScriptType: v4.00+

    [Fonts]
    fontname: CustomEmbedded_0.ttf
    !!""##$$%%&&''(())**++,,--..//00112233445566778899::;;<<==>>??@@

    [Events]
    Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
    Dialogue: 0,0:00:01.00,0:00:03.00,Default,,0,0,0,,Subtitle with embedded UU-encoded font
    """
    let embeddedURL = try fixture.writeRawSubtitle(
        name: "EmbeddedFont.ass",
        data: Data(embeddedFontASS.utf8)
    )
    try fixture.writeVideo(name: "EmbeddedFont.mkv")

    let indexer = SubtitleIndexer()
    let firstRun = try indexer.index(folder: fixture.root, into: fixture.indexingDatabase)
    #expect(firstRun.indexedSubtitleFiles == 1)
    #expect(firstRun.indexedSubtitleEntries == 1)

    // Stored as checked ineligible marker with NULL blob; read-only validation reports unavailable.
    #expect(
        try sqliteStringValue(
            at: fixture.databaseURL,
            sql: "SELECT status FROM ass_event_offset_indexes;"
        ) == "ineligible"
    )
    #expect(
        try sqliteStringValue(
            at: fixture.databaseURL,
            sql: "SELECT typeof(compressed_events) FROM ass_event_offset_indexes;"
        ) == "null"
    )

    let playbackDB = try PlaybackSubtitleDatabase(path: fixture.databaseURL, access: .readOnly)
    #expect(try playbackDB.validatedASSEventOffsetIndex(forSubtitleFile: embeddedURL) == nil)

    // Repeat Index on unchanged folder skips rescanning the checked-ineligible file!
    let secondRun = try indexer.index(folder: fixture.root, into: fixture.indexingDatabase)
    #expect(secondRun.indexedSubtitleFiles == 0)
    #expect(secondRun.skippedUnchangedSubtitleFiles == 1)

    // Mid-stream Format: change after Dialogue: is also marked ineligible rather than mis-slicing columns.
    let midStreamFormatASS = """
    [Script Info]
    ScriptType: v4.00+

    [Events]
    Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
    Dialogue: 0,0:00:01.00,0:00:03.00,Default,,0,0,0,,First format line
    Format: Start, End, Layer, Style, Name, MarginL, MarginR, MarginV, Effect, Text
    Dialogue: 0:00:04.00,0:00:06.00,0,Default,,0,0,0,,Swapped format columns mid-stream
    """
    let midStreamURL = try fixture.writeRawSubtitle(
        name: "MidStreamFormat.ass",
        data: Data(midStreamFormatASS.utf8)
    )
    try fixture.writeVideo(name: "MidStreamFormat.mkv")

    let thirdRun = try indexer.index(folder: fixture.root, into: fixture.indexingDatabase)
    #expect(thirdRun.indexedSubtitleFiles == 1)
    #expect(thirdRun.skippedUnchangedSubtitleFiles == 1)
    #expect(try playbackDB.validatedASSEventOffsetIndex(forSubtitleFile: midStreamURL) == nil)

    // Removing one subtitle file on disk and re-indexing removes its ass_event_offset_indexes row cleanly.
    try FileManager.default.removeItem(at: midStreamURL)
    _ = try indexer.index(folder: fixture.root, into: fixture.indexingDatabase)
    #expect(try sqliteRowCount(in: "ass_event_offset_indexes", databaseURL: fixture.databaseURL) == 1)
}

@Test
func backfillsLegacyUpgradedASSSubtitleOnNextIndexWithoutBreakingCueIDsOrExcerpts() throws {
    let fixture = try ASSEventOffsetTestFixture()
    defer { fixture.cleanUp() }

    let assText = """
    [Script Info]
    ScriptType: v4.00+

    [Events]
    Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
    Dialogue: 0,0:00:02.00,0:00:05.00,Default,,0,0,0,,保存書籤的台詞
    """
    let assURL = try fixture.writeRawSubtitle(name: "LegacyEpisode.ass", data: Data(assText.utf8))
    try fixture.writeVideo(name: "LegacyEpisode.mkv")

    let indexer = SubtitleIndexer()
    _ = try indexer.index(folder: fixture.root, into: fixture.indexingDatabase)

    let playbackDB = try PlaybackSubtitleDatabase(path: fixture.databaseURL)
    let initialCueID = try #require(
        try playbackDB.cueLineRecords(forSubtitleFile: assURL).first?.id
    )
    let excerptDB = try ExcerptDatabase(path: fixture.databaseURL)
    let list = try excerptDB.createExcerptList(name: "Favorites")
    _ = try excerptDB.upsertExcerpt(cueID: initialCueID, listID: list.id)

    // Simulate pre-Schema-67 state: delete only the ass_event_offset_indexes row.
    try executeDatabaseTestSQLite(
        at: fixture.databaseURL,
        "DELETE FROM ass_event_offset_indexes;"
    )
    #expect(try playbackDB.validatedASSEventOffsetIndex(forSubtitleFile: assURL) == nil)

    // Next Index detects missing binary offset index and backfills it without churning cues or Excerpts.
    let backfillRun = try indexer.index(folder: fixture.root, into: fixture.indexingDatabase)
    #expect(backfillRun.indexedSubtitleFiles == 1)
    #expect(!backfillRun.hasIndexedContentChanges)

    let backfilled = try #require(try playbackDB.validatedASSEventOffsetIndex(forSubtitleFile: assURL))
    #expect(backfilled.eventCount == 1)
    let decoded = try #require(
        try backfilled.readAndDecodeEventLines(backfilled.events, from: assURL)
    )
    #expect(decoded == ["Dialogue: 0,0:00:02.00,0:00:05.00,Default,,0,0,0,,保存書籤的台詞"])

    // CueID and Excerpt remain 100% intact.
    let cueIDAfterBackfill = try #require(
        try playbackDB.cueLineRecords(forSubtitleFile: assURL).first?.id
    )
    #expect(cueIDAfterBackfill == initialCueID)
    #expect(try excerptDB.excerpts(listID: list.id).first?.unavailableReason == nil)

    // Subsequent Index skips unchanged file.
    let thirdRun = try indexer.index(folder: fixture.root, into: fixture.indexingDatabase)
    #expect(thirdRun.indexedSubtitleFiles == 0)
    #expect(thirdRun.skippedUnchangedSubtitleFiles == 1)
}

@Test
func invalidatesFingerprintOnExternalEditRefreshesCleansUpAndPreservesAcrossInAppRename() throws {
    let fixture = try ASSEventOffsetTestFixture()
    defer { fixture.cleanUp() }

    let originalASS = """
    [Script Info]
    Title: Original
    ScriptType: v4.00+

    [Events]
    Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
    Dialogue: 0,0:00:01.00,0:00:03.00,Default,,0,0,0,,Original line one
    """
    let assURL = try fixture.writeRawSubtitle(name: "EP01.ass", data: Data(originalASS.utf8))
    let videoURL = try fixture.writeVideo(name: "EP01.mkv")

    let indexer = SubtitleIndexer()
    let firstResult = try indexer.index(folder: fixture.root, into: fixture.indexingDatabase)
    try LibraryDatabase(path: fixture.databaseURL).refreshPresentationAfterIndexedContentChange(
        affectedFolderPaths: Set(firstResult.affectedFolderPaths)
    )

    let readOnlyPlaybackDB = try PlaybackSubtitleDatabase(path: fixture.databaseURL, access: .readOnly)
    #expect(try readOnlyPlaybackDB.validatedASSEventOffsetIndex(forSubtitleFile: assURL)?.eventCount == 1)

    // 1. External edit (inserting header comment shifts byte offsets!) immediately invalidates fingerprint
    //    before Index runs, never returning stale offsets.
    let externallyEditedASS = """
    [Script Info]
    ; Inserted extra comment shifting every subsequent byte offset by 65 bytes!
    Title: Edited Outside App
    ScriptType: v4.00+

    [Events]
    Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
    Dialogue: 0,0:00:01.00,0:00:03.00,Default,,0,0,0,,Edited line one
    Dialogue: 0,0:00:04.00,0:00:06.00,Default,,0,0,0,,Edited line two
    """
    try Data(externallyEditedASS.utf8).write(to: assURL)
    try FileManager.default.setAttributes(
        [.modificationDate: Date().addingTimeInterval(5)],
        ofItemAtPath: assURL.path
    )

    #expect(try readOnlyPlaybackDB.validatedASSEventOffsetIndex(forSubtitleFile: assURL) == nil)

    // 2. Same-byte-size mtime change ALSO invalidates fingerprint.
    let reindexedResult = try indexer.index(folder: fixture.root, into: fixture.indexingDatabase)
    try LibraryDatabase(path: fixture.databaseURL).refreshPresentationAfterIndexedContentChange(
        affectedFolderPaths: Set(reindexedResult.affectedFolderPaths)
    )
    let refreshedIndex = try #require(try readOnlyPlaybackDB.validatedASSEventOffsetIndex(forSubtitleFile: assURL))
    #expect(refreshedIndex.eventCount == 2)

    let shiftedMtime = refreshedIndex.modifiedAt.addingTimeInterval(10)
    #expect(
        try readOnlyPlaybackDB.validatedASSEventOffsetIndex(
            forSubtitleFile: assURL,
            actualFileSize: refreshedIndex.fileSize,
            actualModifiedAt: shiftedMtime
        ) == nil
    )

    // 3. In-App Rename (file-group rename AND folder rename) preserves binary offset index association
    //    at the new paths without running Index!
    let renamer = LibraryRenamer(database: fixture.indexingDatabase)
    let storedVideoPath = try #require(
        try fixture.indexingDatabase.subtitleFiles().first?.videoPath
    )
    _ = videoURL
    let fileRenamePlan = try renamer.checkConflicts(
        .fileGroup(videoPath: storedVideoPath, newBaseName: "EP09")
    )
    try renamer.perform(fileRenamePlan)

    let renamedFileURL = fixture.show.appendingPathComponent("EP09.ass")
    let afterFileRenameIndex = try #require(
        try readOnlyPlaybackDB.validatedASSEventOffsetIndex(forSubtitleFile: renamedFileURL)
    )
    #expect(afterFileRenameIndex.eventCount == 2)
    #expect(
        try afterFileRenameIndex.readAndDecodeEventLines(afterFileRenameIndex.events, from: renamedFileURL) == [
            "Dialogue: 0,0:00:01.00,0:00:03.00,Default,,0,0,0,,Edited line one",
            "Dialogue: 0,0:00:04.00,0:00:06.00,Default,,0,0,0,,Edited line two"
        ]
    )

    let folderRenamePlan = try renamer.checkConflicts(
        .folder(path: fixture.show.path, newName: "Show Renamed")
    )
    try renamer.perform(folderRenamePlan)

    let renamedFolderASSURL = fixture.root
        .appendingPathComponent("Show Renamed", isDirectory: true)
        .appendingPathComponent("EP09.ass")
    let afterFolderRenameIndex = try #require(
        try readOnlyPlaybackDB.validatedASSEventOffsetIndex(forSubtitleFile: renamedFolderASSURL)
    )
    #expect(afterFolderRenameIndex.eventCount == 2)
