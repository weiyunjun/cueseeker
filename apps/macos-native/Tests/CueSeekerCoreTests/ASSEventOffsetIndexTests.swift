private struct ASSEventOffsetTestFixture {
    let root: URL
    let show: URL
    let databaseURL: URL
    let indexingDatabase: IndexingDatabase

    init() throws {
        root = FileManager.default.temporaryDirectory
            .appendingPathComponent("CueSeekerASSEventOffsetTests-\(UUID().uuidString)", isDirectory: true)
        show = root.appendingPathComponent("Show", isDirectory: true)
        databaseURL = root.appendingPathComponent("CueSeeker.sqlite")
        try FileManager.default.createDirectory(at: show, withIntermediateDirectories: true)
        try DatabaseBootstrap.prepare(at: databaseURL)
        indexingDatabase = try IndexingDatabase(path: databaseURL)
    }

    @discardableResult
    func writeVideo(name: String, in directory: URL? = nil) throws -> URL {
        let dir = directory ?? show
        let url = dir.appendingPathComponent(name)
        try Data("video-stub".utf8).write(to: url)
        return url
    }

    @discardableResult
    func writeRawSubtitle(name: String, data: Data, in directory: URL? = nil) throws -> URL {
        let dir = directory ?? show
        let url = dir.appendingPathComponent(name)
        try data.write(to: url)
        return url
    }

    func cleanUp() {
        try? FileManager.default.removeItem(at: root)
    }
}

