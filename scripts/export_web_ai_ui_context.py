#!/usr/bin/env python3
"""Export selected CueSeeker Swift UI sources into one text file.

The output is intended for web AI tools that cannot directly read Swift files.
Each source file is wrapped in explicit begin/end markers so the receiver can
separate files reliably after the content is pasted or uploaded as plain text.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Iterable


SEARCH_UI_FILES = [
    "apps/macos-native/Package.swift",
    "apps/macos-native/Sources/CueSeekerApp/SearchView.swift",
    "apps/macos-native/Sources/CueSeekerApp/SearchTextView.swift",
    "apps/macos-native/Sources/CueSeekerApp/AppState.swift",
    "apps/macos-native/Sources/CueSeekerApp/ContentView.swift",
    "apps/macos-native/Sources/CueSeekerApp/EmptyStateView.swift",
]

PLAYBACK_INSPECTOR_FILES = [
    "apps/macos-native/Sources/CueSeekerApp/PlaybackView.swift",
    "apps/macos-native/Sources/CueSeekerApp/PlaybackControlsView.swift",
    "apps/macos-native/Sources/CueSeekerApp/PlaybackViewModel.swift",
]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Merge the Swift UI files needed for web-AI UI discussion into a "
            "single plain-text document."
        )
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="CueSeeker repository root. Defaults to the parent of scripts/.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("web_ai_ui_swift_context.txt"),
        help="Output txt path. Relative paths are resolved from the repo root.",
    )
    parser.add_argument(
        "--search-only",
        action="store_true",
        help="Only export the search UI files and omit Playback Inspector files.",
    )
    return parser.parse_args()


def selected_files(search_only: bool) -> list[str]:
    if search_only:
        return SEARCH_UI_FILES.copy()

    return SEARCH_UI_FILES + PLAYBACK_INSPECTOR_FILES


def resolve_output_path(repo_root: Path, output: Path) -> Path:
    if output.is_absolute():
        return output

    return repo_root / output


def read_source(repo_root: Path, relative_path: str) -> str:
    path = repo_root / relative_path
    if not path.is_file():
        raise FileNotFoundError(f"Missing expected source file: {relative_path}")

    return path.read_text(encoding="utf-8")


def render_bundle(repo_root: Path, relative_paths: Iterable[str]) -> str:
    lines = [
        "CueSeeker Swift UI Context Bundle",
        "Generated by scripts/export_web_ai_ui_context.py",
        "",
        "Included files:",
    ]
    relative_paths = list(relative_paths)
    lines.extend(f"- {relative_path}" for relative_path in relative_paths)
    lines.append("")

    for relative_path in relative_paths:
        source = read_source(repo_root, relative_path).rstrip()
        lines.extend(
            [
                "=" * 88,
                f'<<<BEGIN FILE path="{relative_path}" language="swift">>>',
                "=" * 88,
                source,
                "=" * 88,
                f'<<<END FILE path="{relative_path}">>>',
                "=" * 88,
                "",
            ]
        )

    return "\n".join(lines)


def main() -> None:
    args = parse_args()
    repo_root = args.repo_root.resolve()
    output_path = resolve_output_path(repo_root, args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    bundle = render_bundle(repo_root, selected_files(args.search_only))
    output_path.write_text(bundle + "\n", encoding="utf-8")
    print(output_path)


if __name__ == "__main__":
    main()
